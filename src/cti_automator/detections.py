"""Detection as Code: YARA and SIGMA proposals from validated analyses."""

from __future__ import annotations

import base64
import hashlib
import re
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Literal
from uuid import NAMESPACE_URL, uuid5

import requests
import yaml
from pydantic import BaseModel, ConfigDict, Field

from cti_automator.config import Settings
from cti_automator.exceptions import DetectionRuleError
from cti_automator.models import IndicatorType, PDFAnalysis
from cti_automator.observability import observe

RuleFormat = Literal["yara", "sigma"]
_DETECTION_NAMESPACE = "cti-automator detection proposal v1"
_YARA_NAME = re.compile(r"^rule\s+CTI_[A-Za-z0-9_]+\s*\{")
_YARA_STRING = re.compile(r'^\s*\$[A-Za-z0-9_]+\s*=\s*"([^"\\]*(?:\\.[^"\\]*)*)"\s*$')
_SIGMA_DATE = re.compile(r"^\d{4}/\d{2}/\d{2}$")
_SIGMA_LOGSOURCES: dict[str, str] = {
    "ip": "firewall",
    "domain": "dns",
    "url": "proxy",
    "hash": "file_event",
}
_SIGMA_FIELDS: dict[str, str] = {
    "ip": "DestinationIp",
    "domain": "QueryName",
    "url": "cs-uri",
    "hash": "Hash",
}


def _slug(value: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9]+", "_", value).strip("_")
    return (slug or "report")[:40]


def _short_digest(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()[:8]


def _rule_id(rule_format: RuleFormat, analysis: PDFAnalysis, group: str) -> str:
    return str(
        uuid5(
            NAMESPACE_URL,
            f"{_DETECTION_NAMESPACE}|{rule_format}|{analysis.source_document}|{group}",
        )
    )


class DetectionRule(BaseModel):
    """One generated rule proposal awaiting human approval."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    rule_format: RuleFormat
    rule_id: str
    filename: str
    content: str
    source_document: str
    status: Literal["proposal"] = "proposal"
    techniques: tuple[str, ...] = ()
    indicator_count: int = Field(default=0, ge=0)

    @property
    def digest(self) -> str:
        """Stable content digest used for duplicate and drift detection."""
        return hashlib.sha256(self.content.encode("utf-8")).hexdigest()

    def summary(self) -> dict[str, object]:
        """Return a serializable summary without the full rule body."""
        return {
            "format": self.rule_format,
            "rule_id": self.rule_id,
            "filename": self.filename,
            "status": self.status,
            "source_document": self.source_document,
            "techniques": list(self.techniques),
            "indicator_count": self.indicator_count,
            "digest": self.digest,
        }


def generate_yara_rule(analysis: PDFAnalysis) -> DetectionRule:
    """Build one YARA proposal combining report indicators into stable strings."""
    supported = (
        IndicatorType.FILE_HASH_MD5,
        IndicatorType.FILE_HASH_SHA1,
        IndicatorType.FILE_HASH_SHA256,
        IndicatorType.DOMAIN,
        IndicatorType.IPV4,
        IndicatorType.IPV6,
        IndicatorType.URL,
    )
    indicators = [
        item for item in analysis.indicators if item.indicator_type in supported
    ]
    if not indicators:
        raise DetectionRuleError("analysis has no indicators usable in YARA rules")
    hash_conditions: list[str] = []
    for item in indicators:
        val = item.value.lower()
        if item.indicator_type == IndicatorType.FILE_HASH_MD5:
            hash_conditions.append(f'hash.md5(0, filesize) == "{_yara_escape(val)}"')
        elif item.indicator_type == IndicatorType.FILE_HASH_SHA1:
            hash_conditions.append(f'hash.sha1(0, filesize) == "{_yara_escape(val)}"')
        elif item.indicator_type == IndicatorType.FILE_HASH_SHA256:
            hash_conditions.append(f'hash.sha256(0, filesize) == "{_yara_escape(val)}"')
    name = f"CTI_{_slug(analysis.source_document)}_{_short_digest(analysis.source_document)}"
    lines = [
        f"rule {name} {{",
        "  meta:",
        f'    id = "{_rule_id("yara", analysis, "all")}"',
        f'    title = "CTI proposal: {analysis.source_document}"',
        '    status = "proposal"',
        '    description = "Generated by cti-automator; human review and approval'
        ' required before deployment."',
        f'    source_document = "{_yara_escape(analysis.source_document)}"',
        f'    techniques = "{_yara_escape(",".join(t.technique_id for t in analysis.ttps))}"',
        f'    created = "{datetime.now(UTC).isoformat()}"',
        f"    indicators = {len(indicators)}",
        "  strings:",
    ]
    for index, item in enumerate(indicators, start=1):
        lines.append(f'    $s{index:02d} = "{_yara_escape(item.value)}"')
    condition_expr = (
        f"any of them or ({' or '.join(hash_conditions)})"
        if hash_conditions
        else "any of them"
    )
    lines.extend(["  condition:", f"    {condition_expr}", "}"])
    content = "\n".join(lines) + "\n"
    rule = DetectionRule(
        rule_format="yara",
        rule_id=_rule_id("yara", analysis, "all"),
        filename=f"{name.lower()}.yar",
        content=content,
        source_document=analysis.source_document,
        techniques=tuple(t.technique_id for t in analysis.ttps),
        indicator_count=len(indicators),
    )
    validate_rule(rule)
    return rule


def generate_sigma_rules(analysis: PDFAnalysis) -> tuple[DetectionRule, ...]:
    """Build one SIGMA proposal per indicator type present in the analysis."""
    groups: dict[str, list[str]] = {}
    for item in analysis.indicators:
        group = _sigma_group(item.indicator_type)
        if group is not None:
            groups.setdefault(group, []).append(item.value)
    if not groups:
        raise DetectionRuleError("analysis has no indicators usable in SIGMA rules")
    rules: list[DetectionRule] = []
    techniques = tuple(t.technique_id for t in analysis.ttps)
    for group in sorted(groups):
        values = sorted(set(groups[group]))
        rule_id = _rule_id("sigma", analysis, group)
        rule = DetectionRule(
            rule_format="sigma",
            rule_id=rule_id,
            filename=(
                f"sigma_{_slug(analysis.source_document)}_{group}"
                f"_{_short_digest(rule_id)}.yml"
            ),
            content=_sigma_content(analysis, group, values, rule_id, techniques),
            source_document=analysis.source_document,
            techniques=techniques,
            indicator_count=len(values),
        )
        validate_rule(rule)
        rules.append(rule)
    return tuple(rules)


def _sigma_group(indicator_type: IndicatorType) -> str | None:
    if indicator_type in {IndicatorType.IPV4, IndicatorType.IPV6}:
        return "ip"
    if indicator_type == IndicatorType.DOMAIN:
        return "domain"
    if indicator_type == IndicatorType.URL:
        return "url"
    if indicator_type in {
        IndicatorType.FILE_HASH_MD5,
        IndicatorType.FILE_HASH_SHA1,
        IndicatorType.FILE_HASH_SHA256,
    }:
        return "hash"
    return None


def _sigma_content(
    analysis: PDFAnalysis,
    group: str,
    values: list[str],
    rule_id: str,
    techniques: tuple[str, ...],
) -> str:
    document: dict[str, object] = {
        "title": f"CTI proposal - {analysis.source_document} - {group} indicators",
        "id": rule_id,
        "status": "experimental",
        "description": (
            "Generated by cti-automator; human review and approval required "
            "before deployment."
        ),
        "references": [analysis.source_document],
        "author": "cti-automator",
        "date": datetime.now(UTC).strftime("%Y/%m/%d"),
        "tags": [f"attack.{t.lower()}" for t in techniques],
        "custom": "cti-automator-proposal",
        "logsource": {"category": _SIGMA_LOGSOURCES[group]},
        "detection": {
            "selection": {_SIGMA_FIELDS[group]: values},
            "condition": "selection",
        },
        "falsepositives": ["Unknown; validate before enabling in production."],
        "level": "high",
    }
    return yaml.safe_dump(
        document, sort_keys=False, allow_unicode=False, default_flow_style=False
    )


def _yara_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def validate_rule(rule: DetectionRule) -> None:
    """Validate structure, syntax and mandatory proposal fields."""
    if rule.rule_format == "yara":
        _validate_yara(rule)
    else:
        _validate_sigma(rule)


def _validate_yara(rule: DetectionRule) -> None:
    lines = rule.content.splitlines()
    if not lines or not _YARA_NAME.match(lines[0]):
        raise DetectionRuleError("YARA rule must start with a bounded rule header")
    stripped = re.sub(r'"(?:[^"\\]|\\.)*"', '""', rule.content)
    if stripped.count("{") != stripped.count("}"):
        raise DetectionRuleError("YARA rule braces are unbalanced")
    meta = stripped.split("meta:", 1)
    if len(meta) < 2 or "condition:" not in meta[1]:
        raise DetectionRuleError("YARA rule is missing meta or condition blocks")
    required = ("status =", "id =", "title =", "source_document =")
    meta_block = meta[1].split("strings:", 1)[0]
    for marker in required:
        if marker not in meta_block:
            raise DetectionRuleError(f"YARA meta is missing required {marker.strip()}")
    if 'status = "proposal"' not in rule.content:
        raise DetectionRuleError('YARA proposals must declare status="proposal"')
    strings = re.search(r"strings:\n(.*?)\n  condition:", rule.content, re.DOTALL)
    if strings is None or not strings.group(1).strip():
        raise DetectionRuleError("YARA rule has no detection strings")
    for line in strings.group(1).splitlines():
        if not _YARA_STRING.match(line):
            raise DetectionRuleError("YARA string literal is malformed")


def _validate_sigma(rule: DetectionRule) -> None:
    try:
        document = yaml.safe_load(rule.content)
    except (yaml.YAMLError, ValueError) as exc:
        raise DetectionRuleError("SIGMA rule is not valid YAML") from exc
    if not isinstance(document, dict):
        raise DetectionRuleError("SIGMA rule must be a mapping")
    for field in (
        "title",
        "id",
        "status",
        "description",
        "logsource",
        "detection",
        "falsepositives",
        "level",
    ):
        if field not in document:
            raise DetectionRuleError(f"SIGMA rule is missing field '{field}'")
    detection = document["detection"]
    if not isinstance(detection, dict) or "selection" not in detection:
        raise DetectionRuleError("SIGMA detection needs a selection block")
    if detection.get("condition") != "selection":
        raise DetectionRuleError("SIGMA condition must reference the selection")
    if document.get("custom") != "cti-automator-proposal":
        raise DetectionRuleError("SIGMA proposals must carry the cti-automator marker")
    date = document.get("date")
    if not isinstance(date, str) or not _SIGMA_DATE.match(date):
        raise DetectionRuleError("SIGMA date must use YYYY/MM/DD")
    tags = document.get("tags", [])
    if not isinstance(tags, list) or any(
        not isinstance(tag, str) or not re.match(r"^attack(\.[a-z0-9_.]+)?$", tag)
        for tag in tags
    ):
        raise DetectionRuleError("SIGMA tags must follow the attack.* taxonomy")


class FileExportResult(BaseModel):
    """Outcome of writing proposals to an authorized local directory."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    written: tuple[str, ...] = ()
    duplicates: tuple[str, ...] = ()
    conflicts: tuple[str, ...] = ()


class FileDetectionExporter:
    """Write rule proposals to disk without overwriting divergent content."""

    def __init__(self, root: Path) -> None:
        resolved = root.resolve()
        if not resolved.is_dir():
            raise DetectionRuleError("detection output directory does not exist")
        self._root = resolved

    def export(self, rules: tuple[DetectionRule, ...]) -> FileExportResult:
        """Persist rules, skipping duplicates and flagging content drift."""
        written: list[str] = []
        duplicates: list[str] = []
        conflicts: list[str] = []
        for rule in rules:
            validate_rule(rule)
            target = self._root / rule.filename
            if rule.rule_format == "yara" and target.suffix != ".yar":
                raise DetectionRuleError("YARA rules must use the .yar extension")
            if rule.rule_format == "sigma" and target.suffix != ".yml":
                raise DetectionRuleError("SIGMA rules must use the .yml extension")
            if target.exists():
                if target.read_text(encoding="utf-8") == rule.content:
                    duplicates.append(rule.filename)
                    continue
                conflicts.append(rule.filename)
                continue
            target.write_text(rule.content, encoding="utf-8")
            written.append(rule.filename)
        return FileExportResult(
            written=tuple(written),
            duplicates=tuple(duplicates),
            conflicts=tuple(conflicts),
        )


def validate_directory(root: Path) -> tuple[int, list[str]]:
    """Validate committed rule files; used by the GitOps CI gate."""
    resolved = root.resolve()
    if not resolved.is_dir():
        raise DetectionRuleError("detection rules directory does not exist")
    errors: list[str] = []
    count = 0
    for path in sorted(resolved.iterdir()):
        if path.suffix not in {".yar", ".yml", ".yaml"}:
            continue
        count += 1
        rule_format: RuleFormat = "yara" if path.suffix == ".yar" else "sigma"
        content = path.read_text(encoding="utf-8")
        rule = DetectionRule(
            rule_format=rule_format,
            rule_id=str(uuid5(NAMESPACE_URL, f"file|{path.name}")),
            filename=path.name,
            content=content,
            source_document="repository",
        )
        try:
            validate_rule(rule)
        except DetectionRuleError as exc:
            errors.append(f"{path.name}: {exc}")
    return count, errors


class PullRequestFile(BaseModel):
    """One rule file staged for a proposal pull request."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    path: str
    content: str


class PullRequestPlan(BaseModel):
    """A fully computed proposal PR; producing it performs no network calls."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    repository: str
    branch: str
    title: str
    body: str
    files: tuple[PullRequestFile, ...] = ()
    rules_directory: str = "detections"

    def summary(self) -> dict[str, object]:
        """Return the plan without file contents for safe display."""
        return {
            "repository": self.repository,
            "branch": self.branch,
            "title": self.title,
            "rules_directory": self.rules_directory,
            "files": [file.path for file in self.files],
            "mode": "dry-run",
        }


class GitHubPullRequestExporter:
    """Create proposal pull requests on explicitly authorized repositories."""

    def __init__(
        self,
        settings: Settings,
        *,
        session: requests.Session | None = None,
    ) -> None:
        self._settings = settings
        self._session = session or requests.Session()

    @observe("detections")
    def plan(
        self,
        analysis: PDFAnalysis,
        rules: tuple[DetectionRule, ...],
        repository: str,
    ) -> PullRequestPlan:
        """Compute the PR proposal offline; submission stays a separate step."""
        self._authorize(repository)
        for rule in rules:
            validate_rule(rule)
        branch = (
            f"cti-proposals/{_slug(analysis.source_document)}-"
            f"{_short_digest(analysis.source_document)}"
        )
        title = f"Detection proposals: {analysis.source_document}"
        body_lines = [
            "Automated detection proposals generated by cti-automator.",
            "",
            f"Source document: {analysis.source_document}",
            "These rules are PROPOSALS and require human review and approval",
            "before any deployment. No automated deployment is performed.",
            "",
            "Rules:",
        ]
        body_lines.extend(
            f"- `{rule.filename}` ({rule.rule_format}, {rule.indicator_count} "
            f"indicators, techniques: {', '.join(rule.techniques) or 'none'})"
            for rule in rules
        )
        return PullRequestPlan(
            repository=repository,
            branch=branch,
            title=title,
            body="\n".join(body_lines),
            files=tuple(
                PullRequestFile(
                    path=f"detections/{rule.filename}", content=rule.content
                )
                for rule in rules
            ),
        )

    def submit(self, plan: PullRequestPlan) -> str:
        """Create the branch, files and PR; refuse to duplicate open proposals."""
        if not self._settings.github_token:
            raise ValueError("GITHUB_TOKEN is required to submit detection proposals")
        self._authorize(plan.repository)
        if self._open_duplicate(plan.repository, plan.title):
            return "duplicate"
        default_branch = self._default_branch(plan.repository)
        base_sha = self._ref_sha(plan.repository, default_branch)
        self._create_branch(plan.repository, plan.branch, base_sha)
        for file in plan.files:
            self._put_file(plan.repository, file, plan.branch)
        return self._create_pull(plan.repository, plan, default_branch)

    def _authorize(self, repository: str) -> None:
        if (
            not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repository)
            or repository not in self._settings.detection_pr_allowlist
        ):
            raise ValueError("Repository is not in CTI_DETECTION_PR_ALLOWLIST")

    def _request(
        self,
        method: str,
        endpoint: str,
        *,
        json_body: dict[str, Any] | None = None,
        accepted: tuple[int, ...] = (200, 201),
    ) -> dict[str, object]:
        headers = {
            "Accept": "application/vnd.github+json",
            "Authorization": f"Bearer {self._settings.github_token}",
        }
        try:
            response = self._session.request(
                method,
                f"https://api.github.com/{endpoint}",
                headers=headers,
                json=json_body,
                timeout=self._settings.request_timeout,
                verify=self._settings.verify_tls,
                allow_redirects=False,
            )
        except requests.RequestException as exc:
            raise DetectionRuleError("GitHub proposal request failed") from exc
        if response.status_code not in accepted:
            raise DetectionRuleError("GitHub rejected the detection proposal")
        payload: object = response.json()
        if not isinstance(payload, dict):
            raise DetectionRuleError("GitHub returned non-object metadata")
        return payload

    def _default_branch(self, repository: str) -> str:
        payload = self._request("GET", f"repos/{repository}")
        branch = payload.get("default_branch")
        if not isinstance(branch, str) or not branch:
            raise DetectionRuleError("GitHub repository has no default branch")
        return branch

    def _ref_sha(self, repository: str, branch: str) -> str:
        payload = self._request("GET", f"repos/{repository}/git/ref/heads/{branch}")
        target = payload.get("object")
        sha = target.get("sha") if isinstance(target, dict) else None
        if not isinstance(sha, str):
            raise DetectionRuleError("GitHub reference has no commit SHA")
        return sha

    def _create_branch(self, repository: str, branch: str, sha: str) -> None:
        self._request(
            "POST",
            f"repos/{repository}/git/refs",
            json_body={"ref": f"refs/heads/{branch}", "sha": sha},
            accepted=(201, 422),
        )

    def _put_file(self, repository: str, file: PullRequestFile, branch: str) -> None:
        encoded = base64.b64encode(file.content.encode("utf-8")).decode("ascii")
        self._request(
            "PUT",
            f"repos/{repository}/contents/{file.path}",
            json_body={
                "message": f"Add detection proposal {file.path}",
                "content": encoded,
                "branch": branch,
            },
        )

    def _open_duplicate(self, repository: str, title: str) -> bool:
        try:
            response = self._session.get(
                f"https://api.github.com/repos/{repository}/pulls",
                headers={
                    "Accept": "application/vnd.github+json",
                    "Authorization": f"Bearer {self._settings.github_token}",
                },
                params={"state": "open", "per_page": "100"},
                timeout=self._settings.request_timeout,
                verify=self._settings.verify_tls,
                allow_redirects=False,
            )
        except requests.RequestException as exc:
            raise DetectionRuleError("GitHub duplicate check failed") from exc
        if response.status_code != 200:
            raise DetectionRuleError("GitHub duplicate check was rejected")
        payload: object = response.json()
        if not isinstance(payload, list):
            raise DetectionRuleError("GitHub returned invalid pull list")
        return any(
            isinstance(pull, dict) and pull.get("title") == title for pull in payload
        )

    def _create_pull(
        self, repository: str, plan: PullRequestPlan, default_branch: str
    ) -> str:
        payload = self._request(
            "POST",
            f"repos/{repository}/pulls",
            json_body={
                "title": plan.title,
                "body": plan.body,
                "head": plan.branch,
                "base": default_branch,
            },
        )
        url = payload.get("html_url")
        return url if isinstance(url, str) else "created"
